"""Make the OpenGL backend's shader header from the port's GLSL 330 ports (src/render/glsl).

    python tools/glsl_shaders.py --upstream DIR --out HEADER [--manifest JSON]

Every shader variant upstream builds (its src/render/CMakeLists.txt vcs_shader(...) calls, the foreach over SAMPLE_MODE
expanded) gets a GLSL twin with the same array name plus `_glsl`, the same entry point and the same NAME=VALUE defines.
The list is read from upstream's CMakeLists, so a variant added there and not here fails the build instead of being
missed. The text is the GLSL body without `#version`: rhi_gl.cpp prepends `#version 330 core` and the device's own
definitions (RHI_ZERO_TO_ONE). Standard library only.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
GLSL = ROOT / "src/render/glsl"

# the vertex stage's position helper: rendering into a texture flips Y so its rows are top-down as in D3D / Vulkan
# (rhi_flipY -1; the window: 1), and D3D's 0..1 clip depth is remapped when GL_ARB_clip_control is missing
VERTEX_PRELUDE = """uniform float rhi_flipY;
void rhiPosition(vec4 p)
{
#if RHI_ZERO_TO_ONE
    gl_Position = vec4(p.x, p.y * rhi_flipY, p.z, p.w);
#else
    gl_Position = vec4(p.x, p.y * rhi_flipY, p.z * 2.0 - p.w, p.w);
#endif
}
"""

CALL = re.compile(r"vcs_shader\(\s*shaders/(\w+)\.hlsl\s+(\w+)\s+(\w+)\s+(\S+)\s+(\S+)((?:\s+[A-Z_]+=\S+)*)\s*\)")


def variants(cmake_text):
    """(hlsl stem, entry, profile, array name, header, [defines]) for every vcs_shader call, foreach expanded."""
    loop = re.search(r"foreach\(mode RANGE (\d+) (\d+)\)(.*?)endforeach\(\)", cmake_text, re.S)
    before = cmake_text[:loop.start()] if loop else cmake_text
    after = cmake_text[loop.end():] if loop else ""
    expanded = []
    if loop:
        for mode in range(int(loop.group(1)), int(loop.group(2)) + 1):
            expanded.append(loop.group(3).replace("${mode}", str(mode)))
    calls = list(CALL.finditer(before)) + [m for text in expanded for m in CALL.finditer(text)] + list(CALL.finditer(after))
    result = []
    for m in calls:
        defines = m.group(6).split()
        result.append((m.group(1), m.group(2), m.group(3), m.group(4), m.group(5), defines))
    return result


def source(stem, entry, profile, defines):
    path = GLSL / (stem + ".glsl")
    if not path.is_file():
        raise RuntimeError(f"no GLSL port of {stem}.hlsl ({path})")
    body = path.read_text(encoding="utf-8")
    if f"ENTRY_{entry}" not in body:
        raise RuntimeError(f"{path.name} has no entry {entry}")
    vertex = profile.startswith("vs")
    lines = [f"#define {'RHI_VERTEX' if vertex else 'RHI_FRAGMENT'} 1", f"#define ENTRY_{entry} 1"]
    for d in defines:
        name, value = d.split("=", 1)
        lines.append(f"#define {name} {value}")
    lines.append("#line 1 1")  # errors point at the .glsl file's own lines (string 1)
    prelude = VERTEX_PRELUDE if vertex else ""
    return "\n".join(lines[:-1]) + "\n" + prelude + lines[-1] + "\n" + body


def c_string(text):
    out = []
    for line in text.splitlines():
        out.append('"' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
    return "\n    ".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--upstream", required=True, type=Path, help="the (overlaid) upstream checkout")
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--manifest", type=Path)
    a = ap.parse_args()
    try:
        cmake = (a.upstream / "src/render/CMakeLists.txt").read_text(encoding="utf-8")
        found = variants(cmake)
        if not found:
            raise RuntimeError("no vcs_shader calls in upstream's src/render/CMakeLists.txt")
        names = set()
        header = ["// Generated by tools/glsl_shaders.py from src/render/glsl: do not edit.", "#pragma once", ""]
        manifest = []
        for stem, entry, profile, name, hlsl_header, defines in found:
            if name in names:
                raise RuntimeError(f"duplicate shader {name}")
            names.add(name)
            text = source(stem, entry, profile, defines)
            header.append(f"// {stem}.glsl {entry} ({profile}) {' '.join(defines)}".rstrip())
            header.append(f"static const char {name}_glsl[] =\n    {c_string(text)};")
            header.append("")
            manifest.append({"name": name, "hlsl": f"shaders/{stem}.hlsl", "glsl": f"src/render/glsl/{stem}.glsl",
                             "entry": entry, "stage": "vertex" if profile.startswith("vs") else "fragment",
                             "defines": defines, "sha256": hashlib.sha256(text.encode()).hexdigest()})
        a.out.parent.mkdir(parents=True, exist_ok=True)
        content = "\n".join(header) + "\n"
        if not a.out.exists() or a.out.read_text(encoding="utf-8") != content:
            a.out.write_text(content, encoding="utf-8")
        if a.manifest:
            a.manifest.write_text(json.dumps({"variants": manifest}, indent=1) + "\n", encoding="utf-8")
        print(f"glsl_shaders: {len(manifest)} variants")
        return 0
    except (OSError, RuntimeError) as e:
        print(f"glsl_shaders: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
